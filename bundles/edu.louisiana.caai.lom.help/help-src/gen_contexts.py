"""Generates contexts_fields.xml of the help bundle: one context help entry (F1) per form field, from the field
help texts of the editor (model support/field-help.properties). The context ids are those of HelpContexts.field(key).
Usage (from the repository root): python bundles/edu.louisiana.caai.lom.help/help-src/gen_contexts.py"""
import html
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
PROPS = os.path.join(ROOT, 'bundles', 'edu.louisiana.caai.lom.model', 'src', 'edu', 'louisiana', 'caai', 'lom',
                     'model', 'support', 'field-help.properties')
OUT = os.path.join(ROOT, 'bundles', 'edu.louisiana.caai.lom.help', 'contexts_fields.xml')
GUIDE = 'PLUGINS_ROOT/edu.louisiana.caai.lom.editor/help/guide.html'


def context_id(key):
    """Like HelpContexts.id: camel case becomes snake case, other characters underscores."""
    out = []
    for i, c in enumerate(key):
        if c.isupper() and i > 0 and key[i - 1].islower():
            out.append('_')
        out.append(c.lower() if c.isalnum() else '_')
    return ''.join(out)


def words(key):
    return re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', key).capitalize()


def read_properties(path):
    entries, section = [], None
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            heading = re.match(r'#\s*---\s*(.+)', line)
            if heading:
                section = heading.group(1).strip()
                continue
            if not line.strip() or line.lstrip().startswith('#') or '=' not in line:
                continue
            key, value = line.split('=', 1)
            entries.append((key.strip(), value.strip(), section))
    return entries


def main():
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<?NLS TYPE="org.eclipse.help.contexts"?>',
           '<!-- Generated by help-src/gen_contexts.py from model support/field-help.properties of the editor; do not edit. -->',
           '<contexts>']
    for key, text, section in read_properties(PROPS):
        title = words(key) + (' (' + section + ')' if section else '')
        out.append('   <context id="field_%s" title="%s">' % (context_id(key), html.escape(title)))
        out.append('      <description>%s</description>' % html.escape(text, quote=False))
        out.append('      <topic href="%s#%s" label="%s in the HLOM Guide"/>' % (GUIDE, key, html.escape(words(key))))
        out.append('      <topic href="html/tasks/edit-forms.html" label="Editing with the Form Pages"/>')
        out.append('   </context>')
    out.append('</contexts>')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
